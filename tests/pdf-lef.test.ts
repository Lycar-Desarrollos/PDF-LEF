test('2. Word-wrapping engine (wrapPdfTextToWidth) strictly respects right margin & Spanish WinAnsi', async () => {
  const doc = await PDFDocument.create();
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const maxWidthPt = 180;
  const fontSize = 11;

  const longSpanishParagraph =
    '“Cláusula de revisión técnica”: este párrafo extenso con acentos (áéíóú, ñ, ¿¡, €) y una palabraGigantescaSinEspaciosDePrueba1234567890ABCDEFGHIJKLMN debe ajustarse automáticamente sin salirse jamás del margen derecho…';

  const lines = wrapPdfTextToWidth(longSpanishParagraph, font, fontSize, maxWidthPt);
  assert.ok(lines.length >= 4, 'Long paragraph must wrap into multiple lines');

  for (const line of lines) {
    const w = font.widthOfTextAtSize(line, fontSize);
    assert.ok(
      w <= maxWidthPt + 0.01,
      `Wrapped line "${line}" width (${w.toFixed(2)}pt) exceeded maxWidthPt (${maxWidthPt}pt)`
    );
  }
});

test('3. Direct native PDF text edit, move, auto-wrap & delete full round-trip without damaging layout', async () => {
  const sampleBytes = await generateShowcaseSamplePdf();
  const tab = await loadPdfIntoTabDocument('Edicion_Nativa.pdf', sampleBytes, DEFAULT_SETTINGS);
  const originalItems = await extractPageTextsForTab(tab, 0);

  // Pick 3 distinct lines on Page 1: one to edit + wrap, one to move, one to delete
  const targetEdit = originalItems.find((i) => i.text.includes('Haz clic sobre cualquier'));
  const targetMove = originalItems.find((i) => i.text.includes('Folio: LEF-2026-0190'));
  const targetDelete = originalItems.find((i) => i.text.includes('DOCUMENTO EJECUTIVO INTERACTIVO'));

  assert.ok(targetEdit && targetMove && targetDelete, 'Expected showcase text items on page 1');

  const longReplacement =
    'Texto editado directamente en PDF-LEF con ajuste automático de línea para que jamás se salga del margen derecho de la hoja aunque el usuario escriba una oración muy larga.';

  tab.nativeTextEdits[targetEdit.id] = {
    ...targetEdit,
    text: longReplacement,
    modified: true,
  };

  const movedX = 0.12;
  const movedY = 0.86;
  tab.nativeTextEdits[targetMove.id] = {
    ...targetMove,
    x: movedX,
    y: movedY,
    modified: true,
  };

  tab.nativeTextEdits[targetDelete.id] = {
    ...targetDelete,
    deleted: true,
    modified: true,
  };

  const compiledBytes = await compileTabToPdfBytes(tab);
  const reloadedTab = await loadPdfIntoTabDocument('Recompilado.pdf', compiledBytes, DEFAULT_SETTINGS);
  const reloadedItems = await extractPageTextsForTab(reloadedTab, 0);
  const allReloadedText = reloadedItems.map((i) => i.text).join(' ');

  // 1) Edited text is present and wrapped into multiple lines that stay strictly inside page width!
  assert.match(allReloadedText, /Texto editado directamente en PDF-LEF/);
  for (const item of reloadedItems) {
    assert.ok(
      item.x + item.width <= 0.995,
      `Item "${item.text}" overflowed right page boundary: x=${item.x.toFixed(3)}, w=${item.width.toFixed(3)}`
    );
  }

  // 2) Moved text is drawn at the new normalized X/Y coordinates (~0.12, ~0.86)
  const relocated = reloadedItems.find(
    (i) => i.text.includes('Folio: LEF-2026-0190') && Math.abs(i.y - movedY) < 0.04
  );
  assert.ok(relocated, 'Moved text must be drawn at target Y in exported PDF');
  assert.ok(
    Math.abs(relocated.x - movedX) < 0.04,
    `Moved text X (${relocated.x.toFixed(3)}) should match target X (${movedX})`
  );

  // 3) Deleted text was cleanly suppressed in live search
  const hitsDeleted = await searchInTabDocument(tab, 'DOCUMENTO EJECUTIVO INTERACTIVO');
  assert.equal(hitsDeleted.length, 0, 'Deleted native text must not appear in live search');
});

