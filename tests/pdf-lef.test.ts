async function extractPageTextsForTab(tab: PdfTabDocument, pageIndex: number) {
  const pd = tab.pages[pageIndex];
  const items = await extractNativeEditableTexts(
    pd.sourceId,
    tab.sourceBuffers[pd.sourceId],
    pd
  );
  tab.extractedPageTexts[pd.id] = items;
  return items;
}

function collectFiles(dir: string, exts: string[]): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const st = statSync(full);
    if (st.isDirectory()) {
      out.push(...collectFiles(full, exts));
    } else if (exts.some((ext) => full.endsWith(ext))) {
      out.push(full);
    }
  }
  return out;
}

