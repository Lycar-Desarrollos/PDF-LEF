test('5. Complete PDF Toolkit: Merge, Split Range, Split ZIP, Remove Pages, CropBox, Compress, Word (.docx) & CSV', async () => {
  const portfolioBytes = readFileSync(join(ROOT, 'pruebas/06_Portafolio_Obra_Proyectos.pdf'));
  const invoiceBytes = readFileSync(join(ROOT, 'pruebas/02_Factura_Fiscal_CFDI.pdf'));

  // A) Merge 2-page portfolio + 1-page invoice = 3 pages
  const mergedBytes = await mergeMultiplePdfBuffers([
    { fileName: 'Portafolio.pdf', bytes: portfolioBytes },
    { fileName: 'Factura.pdf', bytes: invoiceBytes },
  ]);
  const mergedTab = await loadPdfIntoTabDocument('Expediente.pdf', mergedBytes, DEFAULT_SETTINGS);
  assert.equal(mergedTab.pages.length, 3, 'Merged PDF must contain 3 pages');

  // B) Split into individual PDFs inside a .zip archive (1 page per PDF)
  const zipBlob = await splitPdfIntoZip(mergedTab, 1);
  const zipBytes = new Uint8Array(await zipBlob.arrayBuffer());
  const loadedZip = await JSZip.loadAsync(zipBytes);
  const zipFileNames = Object.keys(loadedZip.files);
  assert.equal(zipFileNames.length, 3, 'Split ZIP must contain 3 individual PDF files');
  assert.ok(zipFileNames.some((n) => n.endsWith('_pagina_001.pdf')));

  // C) Remove Page 2 (keep pages 1 and 3) + Rotate Page 1
  const parsedRange = parsePageRangeSpec('1, 3', 3);
  assert.deepEqual(parsedRange, [0, 2]);
  mergedTab.pages[0].rotation = 90;
  const subsetBytes = await extractSelectedPagesAsPdf(mergedTab, parsedRange);
  const subsetDoc = await PDFDocument.load(subsetBytes);
  assert.equal(subsetDoc.getPageCount(), 2, 'Subset after removing page 2 must have 2 pages');
  assert.equal(subsetDoc.getPage(0).getRotation().angle, 90);

  // D) Crop Margins (CropBox / TrimBox)
  const cropTab = await loadPdfIntoTabDocument('Recorte.pdf', invoiceBytes, DEFAULT_SETTINGS);
  cropTab.pages[0].crop = { top: 0.08, right: 0.05, bottom: 0.08, left: 0.05 };
  const croppedBytes = await compileTabToPdfBytes(cropTab);
  const croppedDoc = await PDFDocument.load(croppedBytes);
  const cropBox = croppedDoc.getPage(0).getCropBox();
  assert.ok(cropBox.x > 25 && cropBox.width < 560, 'CropBox must reflect applied normalized margins');

  // E) Compress PDF (lossless object streams)
  const compressedRes = await compressPdfDocument(mergedTab, 'lossless');
  assert.ok(compressedRes.bytes.byteLength > 1000, 'Compressed PDF must be valid and non-empty');
  const compHeader = Buffer.from(compressedRes.bytes.slice(0, 5)).toString('ascii');
  assert.equal(compHeader, '%PDF-');

  // F) PDF to Editable Word (.docx OOXML with reconstructed <w:tbl> tables!)
  const portfolioTab = await loadPdfIntoTabDocument('Portafolio.pdf', portfolioBytes, DEFAULT_SETTINGS);
  const docxBlob = await exportTabToDocxBlob(portfolioTab);
  const docxBytes = new Uint8Array(await docxBlob.arrayBuffer());
  const docxZip = await JSZip.loadAsync(docxBytes);
  assert.ok(docxZip.file('[Content_Types].xml'), '.docx must contain [Content_Types].xml');
  const wordXml = await docxZip.file('word/document.xml')!.async('string');
  assert.match(wordXml, /GP Sercamo S\.A\. de C\.V\./, '.docx must contain portfolio header');
  assert.match(wordXml, /MetroBus L5 - CDMX/, '.docx must contain subtitle');
  assert.match(wordXml, /<w:tbl>/, '.docx must reconstruct Page 2 project table as native <w:tbl>');

  // G) Plain text & UTF-8 CSV export
  const plainTxt = await exportTabToPlainText(portfolioTab);
  assert.match(plainTxt, /Obras Destacadas/);
  const csv = await extractTabTablesToCsv(portfolioTab);
  assert.ok(csv.startsWith('\uFEFF'), 'CSV must start with UTF-8 BOM');
  assert.match(csv, /OBR-104/);
});

