function renderSuiteTools() {
  const container = document.getElementById('suite-tools-container');
  if (!container) return;
  const isEn = currentLang === 'en';
  const filtered = currentCat === 'all' ? SUITE_TOOLS : SUITE_TOOLS.filter((t) => t.cat === currentCat);

  container.innerHTML = filtered
    .map(
      (t) => `
      <article class="suite-tool-card">
        <div class="suite-tool-top">
          <span class="suite-tool-badge ${t.cat}">${isEn ? t.badgeEn : t.badgeEs}</span>
          <span style="font-family:var(--font-mono);font-size:10.5px;color:#94a3b8;">LOCAL</span>
        </div>
        <h4>${isEn ? t.enTitle : t.esTitle}</h4>
        <p>${isEn ? t.enDesc : t.esDesc}</p>
      </article>
    `
    )
    .join('');
}

function renderHeroStage() {
  const stage = document.getElementById('hero-interactive-stage');
  if (stage) {
    stage.innerHTML = getStudioStageHtml(currentMode, currentLang);
  }
  const docLabel = document.getElementById('studio-active-doc');
  if (docLabel) {
    const map = {
      chromatic: '06_Portafolio_Obra_Proyectos.pdf',
      convert: '01_Cotizacion_Comercial_Abasteo.pdf',
      pages: '03_Contrato_Prestacion_Servicios.pdf',
      sign: '05_Certificado_Laboral_Nomina.pdf',
    };
    docLabel.textContent = map[currentMode] || map.chromatic;
  }
}

function applyLanguage(lang) {
  currentLang = lang === 'en' ? 'en' : 'es';
  localStorage.setItem('kova_web_lang', currentLang);
  document.documentElement.lang = currentLang;

  const dict = I18N[currentLang];
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (key && dict[key]) {
      el.textContent = dict[key];
    }
  });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const key = el.getAttribute('data-i18n-html');
    if (key && dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === currentLang);
  });

  renderHeroStage();
  renderSuiteTools();
}

document.querySelectorAll('.lang-btn').forEach((btn) => {
  btn.addEventListener('click', () => {
    applyLanguage(btn.getAttribute('data-lang'));
  });
});

document.querySelectorAll('.studio-mode-btn').forEach((btn) => {
  btn.addEventListener('click', () => {
    document.querySelectorAll('.studio-mode-btn').forEach((b) => b.classList.remove('active'));
    btn.classList.add('active');
    currentMode = btn.getAttribute('data-mode') || 'chromatic';
    renderHeroStage();
  });
});

document.querySelectorAll('.suite-filter-btn').forEach((btn) => {
  btn.addEventListener('click', () => {
    document.querySelectorAll('.suite-filter-btn').forEach((b) => b.classList.remove('active'));
    btn.classList.add('active');
    currentCat = btn.getAttribute('data-cat') || 'all';
    renderSuiteTools();
  });
});

