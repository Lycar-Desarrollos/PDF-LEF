// Auto-resolve direct .exe and .msi installer asset URLs from latest official GitHub Release
fetch('https://api.github.com/repos/Lycar-Desarrollos/PDF-LEF/releases/latest')
  .then((res) => (res.ok ? res.json() : null))
  .then((release) => {
    if (!release || !Array.isArray(release.assets)) return;
    const exeAsset = release.assets.find((a) => a.name && a.name.toLowerCase().endsWith('.exe'));
    if (exeAsset && exeAsset.browser_download_url) {
      ['nav-download-btn', 'hero-download-exe', 'footer-download-exe'].forEach((id) => {
        const el = document.getElementById(id);
        if (el) el.setAttribute('href', exeAsset.browser_download_url);
      });
    }
    const msiAsset = release.assets.find((a) => a.name && a.name.toLowerCase().endsWith('.msi'));
    if (msiAsset && msiAsset.browser_download_url) {
      const msiEl = document.getElementById('hero-download-msi');
      if (msiEl) msiEl.setAttribute('href', msiAsset.browser_download_url);
    }
    if (release.tag_name && exeAsset && exeAsset.size) {
      const sizeMb = (exeAsset.size / (1024 * 1024)).toFixed(1);
      const subEl = document.getElementById('hero-exe-sub');
      if (subEl) {
        subEl.textContent =
          currentLang === 'en'
            ? `Native Installer ${release.tag_name} (.exe · ${sizeMb} MB · 64-bit)`
            : `Instalador Nativo ${release.tag_name} (.exe · ${sizeMb} MB · 64-bit)`;
      }
    }
  })
  .catch(() => {});
